"""Generate fluid property tables for Head Loss from CoolProp.

Usage:
    pip install CoolProp
    python tools/fluidtables/generate.py            # all fluids
    python tools/fluidtables/generate.py air water  # selected fluids

Writes Assets/HeadLoss/Data/fluids/<id>.json and fluids/_sources.md
(06-fluids.md, "Property tables").

Grid: temperature -30 C to 120 C in 2 K steps; absolute pressure 0.8 bar to
50 bar on a log grid (20 points). Liquids (water) are only temperature
dependent at 1 bar, so every pressure row of a liquid repeats the 1 bar values.
Arrays are indexed [pressure][temperature].
"""

import datetime
import json
import math
import os
import sys

import CoolProp
from CoolProp.CoolProp import PropsSI

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
OUT = os.path.join(ROOT, "Assets", "HeadLoss", "Data", "fluids")

T_MIN_C, T_MAX_C, T_STEP = -30.0, 120.0, 2.0
P_MIN, P_MAX, P_COUNT = 0.8e5, 50e5, 20

# id -> (CoolProp name, liquid)
FLUIDS = {
    "air": ("Air", False),
    "water": ("Water", True),
    "natural-gas": ("Methane", False),
    "propane": ("Propane", False),
    "hydrogen": ("Hydrogen", False),
    "oxygen": ("Oxygen", False),
    "nitrogen": ("Nitrogen", False),
    "co2": ("CarbonDioxide", False),
    "refrigerant": ("R32", False),
}


def temperatures():
    n = int(round((T_MAX_C - T_MIN_C) / T_STEP)) + 1
    return [T_MIN_C + i * T_STEP for i in range(n)]


def pressures():
    r = (P_MAX / P_MIN) ** (1.0 / (P_COUNT - 1))
    return [P_MIN * r ** i for i in range(P_COUNT)]


def prop(key, t_k, p, name, liquid):
    """CoolProp property; for liquids evaluated at 1 bar. Falls back to the
    saturated phase on the stable side when the state is two-phase."""
    pp = 1.0e5 if liquid else p
    try:
        return PropsSI(key, "T", t_k, "P", pp, name)
    except ValueError:
        # Near saturation: nudge the pressure into the single-phase region.
        return PropsSI(key, "T", t_k, "P", pp * (0.999 if not liquid else 1.001), name)


def table(fid, name, liquid):
    ts = temperatures()
    ps = pressures()
    out = {
        "fluid": fid,
        "source": f"CoolProp {CoolProp.__version__}, generated {datetime.date.today().isoformat()}",
        "temperaturesC": [round(t, 3) for t in ts],
        "pressuresPa": [round(p, 3) for p in ps],
        "density": [], "viscosity": [], "specificHeat": [], "conductivity": [],
        "molarMass": PropsSI("M", name),
        "gamma": PropsSI("CPMASS", "T", 293.15, "P", 101325, name) / PropsSI("CVMASS", "T", 293.15, "P", 101325, name),
        "speedOfSound20C": PropsSI("A", "T", 293.15, "P", 101325, name),
    }
    for p in ps:
        rho, mu, cp, k = [], [], [], []
        for t in ts:
            tk = t + 273.15
            rho.append(float(f"{prop('D', tk, p, name, liquid):.6g}"))
            mu.append(float(f"{prop('V', tk, p, name, liquid):.6g}"))
            cp.append(float(f"{prop('C', tk, p, name, liquid):.6g}"))
            k.append(float(f"{prop('L', tk, p, name, liquid):.6g}"))
        out["density"].append(rho)
        out["viscosity"].append(mu)
        out["specificHeat"].append(cp)
        out["conductivity"].append(k)
    return out


def main(argv):
    ids = argv[1:] or list(FLUIDS.keys())
    os.makedirs(OUT, exist_ok=True)
    for fid in ids:
        name, liquid = FLUIDS[fid]
        data = table(fid, name, liquid)
        with open(os.path.join(OUT, fid + ".json"), "w", newline="\n") as f:
            json.dump(data, f, separators=(",", ":"))
            f.write("\n")
        print("wrote", fid)
    with open(os.path.join(OUT, "_sources.md"), "w", newline="\n") as f:
        f.write("# Fluid table sources\n\n")
        f.write(f"Generated by `tools/fluidtables/generate.py` with CoolProp {CoolProp.__version__} "
                f"on {datetime.date.today().isoformat()}.\n\n")
        for fid in ids:
            f.write(f"- `{fid}.json`: CoolProp fluid `{FLUIDS[fid][0]}`\n")


if __name__ == "__main__":
    main(sys.argv)
